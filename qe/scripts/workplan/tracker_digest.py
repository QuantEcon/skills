#!/usr/bin/env python3
"""tracker_digest.py — the one-screen digest of a project tracker, computed from its snapshot.

    tracker_snapshot.py owner/repo#7 --json | tracker_digest.py -
    tracker_digest.py .qe/snapshot.json [--out .qe/DIGEST.md]

Everything in the digest is derived from structure the platform holds — the child list,
its states, types, milestones and blocked-by edges, the child bodies' phase markers — and
from three lines of the tracker body: the goal (its first line), the stamp, and the
`**Next:**` line. Nothing is typed, and the digest is never written into the tracker
body: a generated count in a body is a mirror that drifts the moment an item closes.
The output carries a first-line marker naming its source; regenerate it, never edit it.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys

NEXT_LINE = re.compile(r"^\s*\*\*Next:\*\*\s*(?P<text>.*)$", re.M)
NEEDS = re.compile(r"^\s*\*\*(?:Still needing a human|Needs a person|Needs a human|Waiting on a person)[^*]*\*\*\s*(?P<text>.*)$", re.M)


def label(c: dict, t: dict) -> str:
    """#N for a child in the tracker's repository, owner/repo#N elsewhere."""
    return f"#{c['number']}" if c["repo"] == t["repo"] else c["ref"]


def first_line(body: str) -> str:
    for ln in body.splitlines():
        s = ln.strip()
        if s and not s.startswith("#"):
            return s.strip("*_ ")
    return ""


def phase_rows(body: str) -> list[dict]:
    lines = body.splitlines()
    rows = []
    for i, ln in enumerate(lines):
        if ln.lstrip().startswith("|") and re.search(r"\|\s*phase", ln, re.I) and i + 1 < len(lines) and re.match(r"^\s*\|\s*:?-", lines[i + 1]):
            j = i + 2
            while j < len(lines) and lines[j].lstrip().startswith("|"):
                cells = [c.strip() for c in lines[j].strip().strip("|").split("|")]
                label = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", cells[0])
                m = re.search(r"(\d+)", label)
                rows.append({"key": m.group(1) if m else label.lower(), "label": label, "intent": cells[1] if len(cells) > 1 else "", "exit": cells[2] if len(cells) > 2 else ""})
                j += 1
            break
    return rows


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("snapshot", help="path to a JSON snapshot, or - for stdin")
    p.add_argument("--out", help="write the digest here (e.g. .qe/DIGEST.md) instead of stdout")
    a = p.parse_args(argv)
    snap = json.load(sys.stdin if a.snapshot == "-" else open(a.snapshot))
    t, kids = snap["tracker"], snap["children"]
    body = (t.get("body") or "").replace("\r\n", "\n")
    today = dt.datetime.now(dt.timezone.utc).date()
    st = t["stamp"]
    age = (today - dt.date.fromisoformat(st["date"])).days if st.get("date") else None
    total, done = t["sub_issues_summary"]["total"], t["sub_issues_summary"]["completed"]
    pct = f" ({round(100 * done / total)}%)" if total else ""
    decisions = [c for c in kids if c["role"] == "decision"]
    d_open = [c for c in decisions if c["state"] == "open"]
    parked = [c for c in kids if c["state"] == "open" and (c["blocked_by"]["open"] or [])]
    priv = {True: "private", False: "public", None: "visibility unknown"}[t["private"]]

    out = [f"<!-- generated by qe/scripts/workplan/tracker_digest.py from {t['ref']} at {snap['generated_at']}; regenerate, do not edit -->",
           f"# Digest — {t['title']}", "",
           f"`{t['ref']}` · {t['type'] or 'untyped'} · {priv} · stamp: {st['form']}"
           + (f", {st['date']} ({age} day{'s' if age != 1 else ''} old)" if age is not None else "") + f" · {t.get('comments', 0)} comments", ""]
    goal = re.sub(r"^goal:\s*", "", first_line(body), flags=re.I)
    if goal:
        out += [f"**Goal.** {goal}", ""]
    out += [f"**Work.** {total} direct children · {done} closed{pct} · {len(decisions) - len(d_open)} decisions recorded, {len(d_open)} open"
            + (f" · {len(parked)} parked on open blockers" if parked else ""), ""]
    m = NEXT_LINE.search(body)
    if m:
        nxt = m.group("text").strip()
        first = re.split(r"(?<=[.;])\s+(?=\S)", nxt, maxsplit=1)
        rest = len(nxt.split()) - len(first[0].split())
        out += [f"**Next.** {first[0]}" + (f" *(+{rest} words on the tracker)*" if rest > 0 else ""), ""]

    rows = phase_rows(body)
    if rows or any(c.get("milestone") or c.get("phase") for c in kids):
        out += ["| Phase | Exit criterion (from the body) | Items | Done | Open items |", "|---|---|---|---|---|"]
        seen = set()
        for r in rows:
            members = [c for c in kids if c["role"] == "work" and ((c.get("phase") or "").lower() == r["key"] or (c.get("milestone") or "").lower() == r["label"].lower())]
            seen.update(c["ref"] for c in members)
            open_items = ", ".join(label(c, t) for c in members if c["state"] == "open")
            n_done = sum(1 for c in members if c["state"] == "closed")
            items = str(len(members)) if members else "no carrier"
            ex = r["exit"] if len(r["exit"]) <= 80 else r["exit"][:79].rstrip() + "…"
            out.append(f"| {r['label']} | {ex} | {items} | {n_done if members else '—'} | {open_items or ('—' if members else '')} |")
        unassigned = [c for c in kids if c["role"] == "work" and c["ref"] not in seen]
        if unassigned:
            open_un = ", ".join(label(c, t) for c in unassigned if c["state"] == "open")[:120]
            out.append(f"| *no phase marker or milestone* | | {len(unassigned)} | {sum(1 for c in unassigned if c['state'] == 'closed')} | {open_un} |")
        out.append("")
    if d_open:
        out += ["**Decisions open.** " + " · ".join(f"{label(c, t)} — {c['title'][:70]}" + (f" (blocked by {len(c['blocked_by']['open'])})" if c['blocked_by']['open'] else "") for c in d_open), ""]
    if parked:
        out += ["**Parked.** " + " · ".join(f"{label(c, t)} ({', '.join(c['blocked_by']['open'])})" for c in parked), ""]
    n = NEEDS.search(body)
    if n:
        out += [f"**Needs a person.** {n.group('text').strip()[:300]}", ""]
    text = "\n".join(out).rstrip() + "\n"
    if a.out:
        open(a.out, "w").write(text)
        print(f"wrote {a.out}", file=sys.stderr)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
